-- Oracle Database 21c XE schema for the fictional ABES J14 project.
-- Run while connected to XEPDB1 as the application schema owner.
-- This script is intentionally create-only; it contains no DROP or TRUNCATE statements.

CREATE TABLE APP_ROLES (
    ROLE_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ROLE_CODE VARCHAR2(40 CHAR) NOT NULL,
    ROLE_NAME VARCHAR2(80 CHAR) NOT NULL,
    DESCRIPTION VARCHAR2(240 CHAR),
    CONSTRAINT PK_APP_ROLES PRIMARY KEY (ROLE_ID),
    CONSTRAINT UK_APP_ROLES_CODE UNIQUE (ROLE_CODE)
);

CREATE TABLE APP_USERS (
    USER_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    USERNAME VARCHAR2(50 CHAR) NOT NULL,
    DISPLAY_NAME VARCHAR2(120 CHAR) NOT NULL,
    EMAIL VARCHAR2(160 CHAR) NOT NULL,
    PASSWORD_HASH VARCHAR2(100 CHAR) NOT NULL,
    ACTIVE_FLAG CHAR(1 CHAR) DEFAULT 'Y' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_APP_USERS PRIMARY KEY (USER_ID),
    CONSTRAINT UK_APP_USERS_USERNAME UNIQUE (USERNAME),
    CONSTRAINT UK_APP_USERS_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_APP_USERS_ACTIVE CHECK (ACTIVE_FLAG IN ('Y', 'N'))
);

CREATE TABLE APP_USER_ROLES (
    USER_ID NUMBER NOT NULL,
    ROLE_ID NUMBER NOT NULL,
    CONSTRAINT PK_APP_USER_ROLES PRIMARY KEY (USER_ID, ROLE_ID),
    CONSTRAINT FK_USER_ROLES_USER FOREIGN KEY (USER_ID) REFERENCES APP_USERS (USER_ID),
    CONSTRAINT FK_USER_ROLES_ROLE FOREIGN KEY (ROLE_ID) REFERENCES APP_ROLES (ROLE_ID)
);

CREATE TABLE VENDOR_CATEGORIES (
    CATEGORY_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    CATEGORY_CODE VARCHAR2(30 CHAR) NOT NULL,
    CATEGORY_NAME VARCHAR2(100 CHAR) NOT NULL,
    CONSTRAINT PK_VENDOR_CATEGORIES PRIMARY KEY (CATEGORY_ID),
    CONSTRAINT UK_VENDOR_CATEGORIES_CODE UNIQUE (CATEGORY_CODE),
    CONSTRAINT UK_VENDOR_CATEGORIES_NAME UNIQUE (CATEGORY_NAME)
);

CREATE TABLE VENDORS (
    VENDOR_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    VENDOR_CODE VARCHAR2(30 CHAR) NOT NULL,
    VENDOR_NAME VARCHAR2(160 CHAR) NOT NULL,
    CATEGORY_ID NUMBER NOT NULL,
    CITY VARCHAR2(80 CHAR) NOT NULL,
    STATE_NAME VARCHAR2(80 CHAR) NOT NULL,
    PHONE VARCHAR2(15 CHAR) NOT NULL,
    CONTACT_EMAIL VARCHAR2(160 CHAR) NOT NULL,
    ACTIVE_FLAG CHAR(1 CHAR) DEFAULT 'Y' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_VENDORS PRIMARY KEY (VENDOR_ID),
    CONSTRAINT UK_VENDORS_CODE UNIQUE (VENDOR_CODE),
    CONSTRAINT UK_VENDORS_EMAIL UNIQUE (CONTACT_EMAIL),
    CONSTRAINT CK_VENDORS_ACTIVE CHECK (ACTIVE_FLAG IN ('Y', 'N')),
    CONSTRAINT FK_VENDORS_CATEGORY FOREIGN KEY (CATEGORY_ID) REFERENCES VENDOR_CATEGORIES (CATEGORY_ID)
);

CREATE TABLE CONTRACT_STATUSES (
    CONTRACT_STATUS_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    STATUS_CODE VARCHAR2(30 CHAR) NOT NULL,
    STATUS_NAME VARCHAR2(80 CHAR) NOT NULL,
    CONSTRAINT PK_CONTRACT_STATUSES PRIMARY KEY (CONTRACT_STATUS_ID),
    CONSTRAINT UK_CONTRACT_STATUSES_CODE UNIQUE (STATUS_CODE)
);

CREATE TABLE CONTRACTS (
    CONTRACT_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    CONTRACT_NUMBER VARCHAR2(40 CHAR) NOT NULL,
    TITLE VARCHAR2(180 CHAR) NOT NULL,
    VENDOR_ID NUMBER NOT NULL,
    CONTRACT_STATUS_ID NUMBER NOT NULL,
    START_DATE DATE NOT NULL,
    END_DATE DATE NOT NULL,
    CONTRACT_VALUE NUMBER(16,2) NOT NULL,
    SUMMARY VARCHAR2(1000 CHAR) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_CONTRACTS PRIMARY KEY (CONTRACT_ID),
    CONSTRAINT UK_CONTRACTS_NUMBER UNIQUE (CONTRACT_NUMBER),
    CONSTRAINT CK_CONTRACTS_DATES CHECK (END_DATE >= START_DATE),
    CONSTRAINT CK_CONTRACTS_VALUE CHECK (CONTRACT_VALUE > 0),
    CONSTRAINT FK_CONTRACTS_VENDOR FOREIGN KEY (VENDOR_ID) REFERENCES VENDORS (VENDOR_ID),
    CONSTRAINT FK_CONTRACTS_STATUS FOREIGN KEY (CONTRACT_STATUS_ID) REFERENCES CONTRACT_STATUSES (CONTRACT_STATUS_ID)
);

CREATE TABLE REQUISITION_STATUSES (
    REQUISITION_STATUS_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    STATUS_CODE VARCHAR2(30 CHAR) NOT NULL,
    STATUS_NAME VARCHAR2(80 CHAR) NOT NULL,
    CONSTRAINT PK_REQUISITION_STATUSES PRIMARY KEY (REQUISITION_STATUS_ID),
    CONSTRAINT UK_REQUISITION_STATUSES_CODE UNIQUE (STATUS_CODE)
);

CREATE TABLE PROCUREMENT_REQUISITIONS (
    REQUISITION_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    REQUISITION_NUMBER VARCHAR2(40 CHAR) NOT NULL,
    REQUESTED_BY_USER_ID NUMBER NOT NULL,
    REQUISITION_STATUS_ID NUMBER NOT NULL,
    TITLE VARCHAR2(180 CHAR) NOT NULL,
    JUSTIFICATION VARCHAR2(1000 CHAR) NOT NULL,
    NEEDED_BY_DATE DATE NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_PROCUREMENT_REQUISITIONS PRIMARY KEY (REQUISITION_ID),
    CONSTRAINT UK_REQUISITIONS_NUMBER UNIQUE (REQUISITION_NUMBER),
    CONSTRAINT FK_REQUISITIONS_USER FOREIGN KEY (REQUESTED_BY_USER_ID) REFERENCES APP_USERS (USER_ID),
    CONSTRAINT FK_REQUISITIONS_STATUS FOREIGN KEY (REQUISITION_STATUS_ID) REFERENCES REQUISITION_STATUSES (REQUISITION_STATUS_ID)
);

CREATE TABLE REQUISITION_ITEMS (
    REQUISITION_ITEM_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    REQUISITION_ID NUMBER NOT NULL,
    LINE_NUMBER NUMBER(5) NOT NULL,
    ITEM_DESCRIPTION VARCHAR2(240 CHAR) NOT NULL,
    QUANTITY NUMBER(12,3) NOT NULL,
    UNIT_OF_MEASURE VARCHAR2(30 CHAR) NOT NULL,
    ESTIMATED_UNIT_COST NUMBER(16,2) NOT NULL,
    CONSTRAINT PK_REQUISITION_ITEMS PRIMARY KEY (REQUISITION_ITEM_ID),
    CONSTRAINT UK_REQUISITION_LINE UNIQUE (REQUISITION_ID, LINE_NUMBER),
    CONSTRAINT CK_REQUISITION_LINE_NUMBER CHECK (LINE_NUMBER > 0),
    CONSTRAINT CK_REQUISITION_QUANTITY CHECK (QUANTITY > 0),
    CONSTRAINT CK_REQUISITION_UNIT_COST CHECK (ESTIMATED_UNIT_COST >= 0),
    CONSTRAINT FK_REQUISITION_ITEMS_REQUEST FOREIGN KEY (REQUISITION_ID) REFERENCES PROCUREMENT_REQUISITIONS (REQUISITION_ID)
);

CREATE TABLE VENDOR_EVALUATIONS (
    EVALUATION_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    REQUISITION_ID NUMBER NOT NULL,
    VENDOR_ID NUMBER NOT NULL,
    EVALUATED_BY_USER_ID NUMBER NOT NULL,
    SCORE NUMBER(5,2) NOT NULL,
    RECOMMENDATION VARCHAR2(1000 CHAR) NOT NULL,
    EVALUATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_VENDOR_EVALUATIONS PRIMARY KEY (EVALUATION_ID),
    CONSTRAINT UK_EVALUATION_VENDOR_REQUEST UNIQUE (REQUISITION_ID, VENDOR_ID),
    CONSTRAINT CK_VENDOR_SCORE CHECK (SCORE BETWEEN 0 AND 100),
    CONSTRAINT FK_EVALUATIONS_REQUEST FOREIGN KEY (REQUISITION_ID) REFERENCES PROCUREMENT_REQUISITIONS (REQUISITION_ID),
    CONSTRAINT FK_EVALUATIONS_VENDOR FOREIGN KEY (VENDOR_ID) REFERENCES VENDORS (VENDOR_ID),
    CONSTRAINT FK_EVALUATIONS_USER FOREIGN KEY (EVALUATED_BY_USER_ID) REFERENCES APP_USERS (USER_ID)
);

CREATE TABLE INVOICE_STATUSES (
    INVOICE_STATUS_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    STATUS_CODE VARCHAR2(30 CHAR) NOT NULL,
    STATUS_NAME VARCHAR2(80 CHAR) NOT NULL,
    CONSTRAINT PK_INVOICE_STATUSES PRIMARY KEY (INVOICE_STATUS_ID),
    CONSTRAINT UK_INVOICE_STATUSES_CODE UNIQUE (STATUS_CODE)
);

CREATE TABLE INVOICES (
    INVOICE_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    INVOICE_NUMBER VARCHAR2(50 CHAR) NOT NULL,
    CONTRACT_ID NUMBER NOT NULL,
    INVOICE_STATUS_ID NUMBER NOT NULL,
    INVOICE_DATE DATE NOT NULL,
    DUE_DATE DATE NOT NULL,
    TOTAL_AMOUNT NUMBER(16,2) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_INVOICES PRIMARY KEY (INVOICE_ID),
    CONSTRAINT UK_INVOICES_NUMBER UNIQUE (INVOICE_NUMBER),
    CONSTRAINT CK_INVOICE_DATES CHECK (DUE_DATE >= INVOICE_DATE),
    CONSTRAINT CK_INVOICE_AMOUNT CHECK (TOTAL_AMOUNT > 0),
    CONSTRAINT FK_INVOICES_CONTRACT FOREIGN KEY (CONTRACT_ID) REFERENCES CONTRACTS (CONTRACT_ID),
    CONSTRAINT FK_INVOICES_STATUS FOREIGN KEY (INVOICE_STATUS_ID) REFERENCES INVOICE_STATUSES (INVOICE_STATUS_ID)
);

CREATE TABLE PAYMENT_STATUSES (
    PAYMENT_STATUS_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    STATUS_CODE VARCHAR2(30 CHAR) NOT NULL,
    STATUS_NAME VARCHAR2(80 CHAR) NOT NULL,
    CONSTRAINT PK_PAYMENT_STATUSES PRIMARY KEY (PAYMENT_STATUS_ID),
    CONSTRAINT UK_PAYMENT_STATUSES_CODE UNIQUE (STATUS_CODE)
);

CREATE TABLE PAYMENTS (
    PAYMENT_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    INVOICE_ID NUMBER NOT NULL,
    PAYMENT_STATUS_ID NUMBER NOT NULL,
    PAYMENT_REFERENCE VARCHAR2(50 CHAR) NOT NULL,
    PAYMENT_DATE DATE NOT NULL,
    AMOUNT NUMBER(16,2) NOT NULL,
    PAYMENT_METHOD VARCHAR2(30 CHAR) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_PAYMENTS PRIMARY KEY (PAYMENT_ID),
    CONSTRAINT UK_PAYMENT_REFERENCE UNIQUE (PAYMENT_REFERENCE),
    CONSTRAINT CK_PAYMENT_AMOUNT CHECK (AMOUNT > 0),
    CONSTRAINT FK_PAYMENTS_INVOICE FOREIGN KEY (INVOICE_ID) REFERENCES INVOICES (INVOICE_ID),
    CONSTRAINT FK_PAYMENTS_STATUS FOREIGN KEY (PAYMENT_STATUS_ID) REFERENCES PAYMENT_STATUSES (PAYMENT_STATUS_ID)
);

CREATE INDEX IX_APP_USER_ROLES_ROLE ON APP_USER_ROLES (ROLE_ID);
CREATE INDEX IX_VENDORS_CATEGORY ON VENDORS (CATEGORY_ID);
CREATE INDEX IX_CONTRACTS_VENDOR ON CONTRACTS (VENDOR_ID);
CREATE INDEX IX_CONTRACTS_STATUS ON CONTRACTS (CONTRACT_STATUS_ID);
CREATE INDEX IX_REQUISITIONS_REQUESTER ON PROCUREMENT_REQUISITIONS (REQUESTED_BY_USER_ID);
CREATE INDEX IX_REQUISITIONS_STATUS ON PROCUREMENT_REQUISITIONS (REQUISITION_STATUS_ID);
CREATE INDEX IX_REQ_ITEMS_REQUEST ON REQUISITION_ITEMS (REQUISITION_ID);
CREATE INDEX IX_EVALUATIONS_VENDOR ON VENDOR_EVALUATIONS (VENDOR_ID);
CREATE INDEX IX_EVALUATIONS_USER ON VENDOR_EVALUATIONS (EVALUATED_BY_USER_ID);
CREATE INDEX IX_INVOICES_CONTRACT ON INVOICES (CONTRACT_ID);
CREATE INDEX IX_INVOICES_STATUS_DUE ON INVOICES (INVOICE_STATUS_ID, DUE_DATE);
CREATE INDEX IX_PAYMENTS_INVOICE ON PAYMENTS (INVOICE_ID);
CREATE INDEX IX_PAYMENTS_STATUS ON PAYMENTS (PAYMENT_STATUS_ID);
